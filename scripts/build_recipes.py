"""Generate Recipes.lua, the recipes the plugin looks for, from fuji-recipes.csv."""
import csv
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
PLUGIN = ROOT / 'fuji-recipe.lrplugin'


def lua_string(text):
    return '"' + str(text).replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\r', '') + '"'

# CSV names -> film simulation labels of FujiFormat.lua.
FILMS = {
    'Provia/Standard': 'PROVIA', 'Astia/Soft': 'ASTIA', 'Velvia/Vivid': 'VELVIA',
    'PRO Neg. Std': 'PRO NEG. STD', 'PRO Neg. Hi': 'PRO NEG. HI',
    'Classic Chrome': 'CLASSIC CHROME', 'Eterna/Cinema': 'ETERNA',
    'Classic Negative': 'CLASSIC NEG.', 'Eterna Bleach Bypass': 'BLEACH BYPASS',
    'Nostalgic Negative': 'NOSTALGIC NEG.', 'Reala Ace': 'REALA ACE',
    'Monochrome': 'MONOCHROME', 'Monochrome+R': 'MONOCHROME +R',
    'Monochrome+Ye': 'MONOCHROME +Y', 'Monochrome+G': 'MONOCHROME +G', 'Sepia': 'SEPIA',
    'Acros': 'ACROS', 'Acros+R': 'ACROS +R', 'Acros+Ye': 'ACROS +Y', 'Acros+G': 'ACROS +G',
}
# Preserve the numbered fluorescent presets and the fixed DR-priority strength.
WHITE = {
    'Auto': 'auto', 'Auto (White Priority)': 'auto-white',
    'Auto (Ambience Priority)': 'auto-ambience', 'Daylight': 'daylight', 'Shade': 'shade',
    'Fluorescent 1': 'fluorescent-1', 'Fluorescent 2': 'fluorescent-2',
    'Fluorescent 3': 'fluorescent-3', 'Incandescent': 'incandescent',
    'Underwater': 'underwater',
}
DYNAMIC_RANGE = {'Auto': 'auto', 'DR100': 100, 'DR200': 200, 'DR400': 400}
DR_PRIORITY = {'Off': 'off', 'Weak': 'weak', 'Strong': 'strong'}
LEVELS = {'Off': 'off', 'Weak': 'weak', 'Strong': 'strong'}
SIZES = {'Small': 'small', 'Large': 'large'}


def choose(row, column, table, required=False):
    value = row[column].strip()
    if not value:
        if required:
            raise SystemExit(row['nom'] + ' : ' + column + ' est vide')
        return None
    if value not in table:
        raise SystemExit(row['nom'] + ' : ' + column + ' « ' + value + ' » inconnu ; valeurs connues : '
            + ', '.join(table))
    return table[value]


def number(row, column):
    value = row[column].strip()
    if not value:
        return None
    try:
        result = float(value)
    except ValueError:
        raise SystemExit(row['nom'] + ' : ' + column + ' « ' + value + ' » n’est pas un nombre')
    return int(result) if result == int(result) else result


def convert(row):
    """Settings of one recipe in the vocabulary of FujiFormat.settings; blanks are left out.

    mono_color_wc and mono_color_mg are not compared: only 0 is validated against
    the MakerNotes, not the scale of other values.
    """
    priority = choose(row, 'dr_priority', DR_PRIORITY, required=True)
    dr = choose(row, 'dynamic_range', DYNAMIC_RANGE)
    if priority != 'off' and dr is not None:
        raise SystemExit(row['nom'] + ' : la priorité DR remplace la plage dynamique, qui doit rester vide')
    kelvin = re.fullmatch(r'(\d{4,5})K', row['white_balance'].strip())
    fields = {
        'name': row['nom'], 'source': row['source'],
        'film': choose(row, 'film_simulation', FILMS, required=True),
        'dr': dr, 'drPriority': priority,
        'wb': 'kelvin' if kelvin else choose(row, 'white_balance', WHITE, required=True),
        'kelvin': int(kelvin.group(1)) if kelvin else None,
        'shiftR': number(row, 'wb_shift_red'), 'shiftB': number(row, 'wb_shift_blue'),
        'highlight': number(row, 'highlight'), 'shadow': number(row, 'shadow'),
        'color': number(row, 'color'),
        'grain': choose(row, 'grain_effect', LEVELS, required=True),
        'grainSize': choose(row, 'grain_size', SIZES),
        'chrome': choose(row, 'color_chrome_effect', LEVELS, required=True),
        'chromeBlue': choose(row, 'color_chrome_fx_blue', LEVELS, required=True),
        'sharpness': number(row, 'sharpness'), 'noise': number(row, 'high_iso_nr'),
        'clarity': number(row, 'clarity'),
    }
    return {key: value for key, value in fields.items() if value is not None}


def lua_value(value):
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, (int, float)):
        return repr(value)
    return lua_string(value)


def build(rows):
    names = [row['nom'] for row in rows]
    if len(set(names)) != len(names):
        raise SystemExit('Noms de recettes en double dans fuji-recipes.csv')
    lua = ['-- Generated by scripts/build_recipes.py. Source: fuji-recipes.csv', 'return {']
    for row in rows:
        fields = convert(row)
        lua.append('    { ' + ', '.join(key + ' = ' + lua_value(value) for key, value in fields.items()) + ' },')
    lua.append('}')
    return '\n'.join(lua) + '\n'


def main():
    with open(ROOT / 'fuji-recipes.csv', encoding='utf-8', newline='') as source:
        rows = list(csv.DictReader(source))
    (PLUGIN / 'Recipes.lua').write_text(build(rows), encoding='utf-8')
    print(len(rows), 'recettes')


if __name__ == '__main__': main()
